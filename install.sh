ROLLBACK="$LIB_DIR/ufw-rollback"
UNIT=/etc/systemd/system/ufw-reloaded.service
SERVICE=ufw-reloaded.service

PORT="$DEFAULT_PORT"
PUBKEY=""
PUBKEY_FILE=""
LABEL=""
FROM_CIDR=""
LISTEN=""
ACTION=install
ASSUME_YES=0

# ---------------------------------------------------------------- utilities

