#!/bin/sh
# ufw-reloaded agent installer
#
# Installs a dedicated, hardened sshd on port 2026 whose only permitted action
# is to run the ufw-reloaded agent. It NEVER reads or modifies
# /etc/ssh/sshd_config, and nothing it does can affect your existing SSH on
# port 22 — stopping or removing this service cannot lock you out.
#
#   Install:    sudo sh install.sh
#               Installs and prints a one-time PAIRING CODE. Type that into the
#               app and it enrols itself. Nothing to copy back, nothing to
#               compare by eye. This is the normal path.
#
#   Pair again: sudo sh install.sh --pair
#               Opens another 15-minute window on an already-installed host —
#               for a second workstation, or if a code expired.
#               --pair-window <minutes>   change the window (1-60)
#               --pair --cancel           close it early
#
#   Scripted:   sudo sh install.sh --pubkey 'ssh-ed25519 AAAA... label'
#               sudo sh install.sh --pubkey-file /tmp/key.pub
#               (--pubkey-file avoids shell quoting trouble when scripted)
#   Add a key:  sudo sh install.sh --add-key --label laptop --pubkey 'ssh-ed25519 ...'
#   Remove:     sudo sh install.sh --remove-key laptop
#   List:       sudo sh install.sh --list-keys
#   Status:     sudo sh install.sh --status
#   Uninstall:  sudo sh install.sh --uninstall
#
# Everything below lives in functions with a single main "$@" at the very end,
# inside a { } block, so a truncated download cannot execute half a script.

{

set -eu

# Not named VERSION: preflight sources /etc/os-release, which defines VERSION
# and would silently overwrite it.
INSTALLER_VERSION="0.1.0"
DEFAULT_PORT=2026

ETC_DIR=/etc/ufw-reloaded
LIB_DIR=/usr/libexec/ufw-reloaded
STATE_DIR=/var/lib/ufw-reloaded
KEYS_DIR="$ETC_DIR/keys.d"
AUTH_KEYS="$ETC_DIR/authorized_keys"
SSHD_CONFIG="$ETC_DIR/sshd_config"
