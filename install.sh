# A directory is safe to install a root-run program into only if it and every
# parent are root-owned and not group- or world-writable. /usr/local/lib is
# root:staff 2775 on Debian and Ubuntu, which is why we use /usr/libexec.
path_is_secure() {
  _p=$1
  while :; do
    [ -e "$_p" ] || { _p=$(dirname "$_p"); continue; }
    _owner=$(stat -c '%u' "$_p" 2>/dev/null || echo 1)
    _mode=$(stat -c '%a' "$_p" 2>/dev/null || echo 777)
    [ "$_owner" = 0 ] || return 1
    # Reject group- or other-writable. In an octal mode the write bit is set for
    # the digits 2, 3, 6 and 7; the second pattern checks the group digit.
    case "$_mode" in
      *[2367]|*[2367]?) return 1 ;;
    esac
    if [ "$_p" = "/" ]; then
      return 0
    fi
    _p=$(dirname "$_p")
  done
}

# ---------------------------------------------------------------- preflight

preflight() {
  say "Checking this host..."
  need_root

  have systemctl || die "systemd is required"
  have ufw       || die "ufw is not installed"
  have sshd || [ -x /usr/sbin/sshd ] || die "openssh-server is not installed"
  have python3   || die "python3 is not installed"
  have ssh-keygen || die "ssh-keygen is not available (install openssh-client)"

  if [ ! -r /etc/os-release ]; then
    die "cannot identify this distribution"
  fi
  . /etc/os-release
  case "${ID:-}${ID_LIKE:-}" in
    *debian*|*ubuntu*) ok "distribution: ${PRETTY_NAME:-$ID}" ;;
    *) die "only Debian and Ubuntu are supported (found ${PRETTY_NAME:-$ID})" ;;
  esac

  SSHD_BIN=$(command -v sshd || echo /usr/sbin/sshd)
  ok "sshd: $SSHD_BIN (OpenSSH $(openssh_version | tr ' ' '.'))"
  ok "python3: $(python3 --version 2>&1)"
  ok "ufw: $(ufw version 2>/dev/null | head -1 || echo unknown)"

  if ! path_is_secure /usr/libexec; then
    die "/usr/libexec is not root-owned and unwritable by others; refusing to install"
  fi

  # Port must be free, or already ours.
  if have ss && ss -ltnH 2>/dev/null | awk '{print $4}' | grep -q ":$PORT\$"; then
    if systemctl is-active --quiet "$SERVICE" 2>/dev/null; then
      ok "port $PORT already in use by this agent (reinstall)"
    else
      die "port $PORT is already in use by something else"
    fi
  fi

  # Things that change what the firewall actually does. Warnings, not errors.
  if [ -S /var/run/docker.sock ] || [ -d /etc/docker ]; then
    warn "Docker is present. Published container ports bypass ufw entirely"
    warn "    (they land in DOCKER-USER), so the app cannot see or control them."
  fi
  [ -d /etc/fail2ban ] && warn "fail2ban is present; 'ufw reload' transiently flushes its bans."
  have firewalld && warn "firewalld is present and conflicts with ufw."
  say ""
}

# ------------------------------------------------------------ key management

validate_pubkey() {
  # A second line would become a second authorized_keys entry, so check that
  # first. `wc -l` counts newlines: a single line with no trailing newline is 0.
  if [ "$(printf '%s' "$1" | wc -l)" -gt 0 ]; then
    die "public key must be a single line"
  fi
  # Then reject anything ssh-keygen itself will not parse, before it reaches a
  # file that sshd reads.
  printf '%s\n' "$1" > "$TMPDIR_/pk"
  ssh-keygen -l -f "$TMPDIR_/pk" >/dev/null 2>&1 \
    || die "that does not look like an SSH public key"
}

fingerprint_of() {
  printf '%s\n' "$1" > "$TMPDIR_/fp"
  ssh-keygen -l -f "$TMPDIR_/fp" 2>/dev/null | awk '{print $2}'
}

# authorized_keys is GENERATED from keys.d and never hand-edited, so adding and
# removing keys cannot corrupt it and re-running is always idempotent.
regenerate_authorized_keys() {
  _restrict=$(key_options)
  _tmp="$AUTH_KEYS.tmp"
  : > "$_tmp"
  chmod 0600 "$_tmp"
  for _f in "$KEYS_DIR"/*.pub; do
    [ -e "$_f" ] || continue
    _id=$(basename "$_f" .pub)
    # head -1, not cat: a second line in a key file would become a second
    # authorized_keys entry, and only the first one carries the forced command.
    # add_key already rejects multi-line input; this makes the file that grants
    # access safe regardless of how it got there.
    _key=$(head -1 "$_f")
    printf '%s,command="%s --client=%s" %s\n' \
      "$_restrict" "$AGENT" "$_id" "$_key" >> "$_tmp"
  done
  chown 0:0 "$_tmp"
  chmod 0600 "$_tmp"
  mv -f "$_tmp" "$AUTH_KEYS"
}

# `sshd -V` only exists on newer OpenSSH; on older builds it errors and prints
# usage, which happens to include the version banner. `ssh -V` is reliable
# everywhere, so try that first and fall back.
openssh_version() {
  # sed exits 0 even when it matches nothing, so test the OUTPUT rather than the
  # exit status — otherwise the fallback would never run.
  _v=$({ ssh -V; } 2>&1 | head -1 | sed -n 's/.*OpenSSH_\([0-9]*\)\.\([0-9]*\).*/\1 \2/p')
  if [ -z "$_v" ]; then
    _v=$({ "$SSHD_BIN" -V; } 2>&1 | head -1 | sed -n 's/.*OpenSSH_\([0-9]*\)\.\([0-9]*\).*/\1 \2/p')
  fi
  printf '%s' "$_v"
}

# `restrict` arrived in OpenSSH 7.2 and is preferred because it is
# forward-compatible: future restrictions apply automatically. On older sshd it
# is an UNKNOWN option, and sshd then rejects the entire key line — so the two
# forms can never both be emitted.
key_options() {
  _v=$(openssh_version)
  _major=$(printf '%s' "$_v" | awk '{print $1}')
  _minor=$(printf '%s' "$_v" | awk '{print $2}')
  if [ -n "$_major" ] && { [ "$_major" -gt 7 ] || { [ "$_major" -eq 7 ] && [ "$_minor" -ge 2 ]; }; }; then
    printf 'restrict'
  else
    printf 'no-port-forwarding,no-agent-forwarding,no-X11-forwarding,no-pty,no-user-rc'
  fi
}

add_key() {
  [ -n "$PUBKEY" ] || die "--pubkey is required"
  [ -d "$ETC_DIR" ] || die "the agent is not installed on this host yet"
  validate_pubkey "$PUBKEY"
  [ -n "$LABEL" ] || LABEL=$(printf '%s' "$PUBKEY" | awk '{print $3}' | tr -c 'A-Za-z0-9._-' '_')
  [ -n "$LABEL" ] || LABEL="client"
  case "$LABEL" in
    *[!A-Za-z0-9._-]*) die "label may only contain letters, digits, dot, underscore and dash" ;;
  esac

  install -d -m 0700 -o root -g root "$KEYS_DIR"
  printf '%s\n' "$PUBKEY" > "$KEYS_DIR/$LABEL.pub"
  chown 0:0 "$KEYS_DIR/$LABEL.pub"
  chmod 0600 "$KEYS_DIR/$LABEL.pub"
  regenerate_authorized_keys
  ok "key '$LABEL' installed ($(fingerprint_of "$PUBKEY"))"
}

remove_key() {
  _id=$1
  [ -n "$_id" ] || die "--remove-key needs a label"
  [ -f "$KEYS_DIR/$_id.pub" ] || die "no key labelled '$_id'"
  rm -f "$KEYS_DIR/$_id.pub"
  regenerate_authorized_keys
  ok "key '$_id' removed"
  if [ -z "$(ls -A "$KEYS_DIR" 2>/dev/null)" ]; then
    warn "no keys remain; the app can no longer connect to this host."
  fi
}

list_keys() {
  [ -d "$KEYS_DIR" ] || die "agent is not installed"
  say "Enrolled keys:"
  _found=0
  for _f in "$KEYS_DIR"/*.pub; do
    [ -e "$_f" ] || continue
    _found=1
    info "$(basename "$_f" .pub)  $(ssh-keygen -l -f "$_f" 2>/dev/null | awk '{print $2}')"
  done
  [ "$_found" = 1 ] || info "(none)"
}

# ------------------------------------------------------------------- install

write_sshd_config() {
  cat > "$SSHD_CONFIG.tmp" <<EOF
# ufw-reloaded dedicated sshd — generated by install.sh $INSTALLER_VERSION
# This file is read ONLY by the ufw-reloaded service. The system sshd on port
# 22 uses /etc/ssh/sshd_config and is not affected by anything here.

Port $PORT
${LISTEN:+ListenAddress $LISTEN}

HostKey $HOST_KEY

# Only root, only by key, and only to run the forced command in authorized_keys.
PermitRootLogin forced-commands-only
# AuthorizedKeysFile is one absolute path with no %u, so it applies to EVERY
# account, not just root — PermitRootLogin only constrains root. Without this an
# enrolled key could also authenticate as any other local user; the forced
# command would then run as them and the agent would refuse (it requires euid 0),
# but that is a door we never meant to leave open.
AllowUsers root
AuthorizedKeysFile $AUTH_KEYS
PubkeyAuthentication yes
PasswordAuthentication no
HostbasedAuthentication no
PermitEmptyPasswords no
# Everything except a public key is refused outright, which is also why the
# keyboard-interactive keywords are omitted: they were renamed in OpenSSH 8.7
# and naming either one breaks sshd -t on some supported release.
AuthenticationMethods publickey

# No PAM: the agent needs no session setup, and PAM would add a dependency on
# LDAP/SSSD being reachable for the firewall tool to work.
UsePAM no

# The client must not be able to set environment variables — that is how
# PYTHONPATH and friends would reach a root Python process.
PermitUserEnvironment no

# Nothing but the forced command. Without these the key would be a network
# pivot into this host's internal network even though it cannot get a shell.
AllowTcpForwarding no
AllowAgentForwarding no
AllowStreamLocalForwarding no
GatewayPorts no
PermitTunnel no
PermitOpen none
X11Forwarding no
PermitTTY no

# No sftp subsystem: the key must not be able to read or write files.

MaxAuthTries 3
MaxSessions 4
MaxStartups 3:50:10
LoginGraceTime 20
ClientAliveInterval 30
ClientAliveCountMax 4

StrictModes yes
PidFile /run/ufw-reloaded/sshd.pid
SyslogFacility AUTHPRIV
LogLevel VERBOSE
PrintMotd no
PrintLastLog no
EOF
  chown 0:0 "$SSHD_CONFIG.tmp"
  chmod 0600 "$SSHD_CONFIG.tmp"
  mv -f "$SSHD_CONFIG.tmp" "$SSHD_CONFIG"

  # Validate before anything depends on it. -t exits non-zero on a bad config.
  "$SSHD_BIN" -t -f "$SSHD_CONFIG" || die "generated sshd config failed validation"
  ok "sshd config written and validated"
}

write_unit() {
  cat > "$UNIT" <<EOF
[Unit]
Description=ufw-reloaded agent (dedicated sshd on port $PORT)
Documentation=https://github.com/gencaps/UFW-Reloaded
After=network.target auditd.service
# Deliberately independent of ssh.service: this must never be able to affect
# the system sshd, and stopping it must never affect port 22.

[Service]
Type=simple
# RuntimeDirectory creates /run/ufw-reloaded with the mode below, so no
# ExecStartPre is needed (and one referencing a binary path would be one more
# thing to be wrong about across distributions).
ExecStart=$SSHD_BIN -D -e -f $SSHD_CONFIG
ExecReload=/bin/kill -HUP \$MAINPID
KillMode=process
Restart=on-failure
RestartSec=5s
RuntimeDirectory=ufw-reloaded
RuntimeDirectoryMode=0700

[Install]
WantedBy=multi-user.target
EOF
  chown 0:0 "$UNIT"
  chmod 0644 "$UNIT"
  systemctl daemon-reload
  ok "systemd unit installed"
}

install_agent_files() {
  install -d -m 0755 -o root -g root "$LIB_DIR"
  install -d -m 0700 -o root -g root "$ETC_DIR"
  install -d -m 0700 -o root -g root "$STATE_DIR"

  # A bundled installer carries the agent inside it; a checkout has it alongside.
  if embedded_agent > "$TMPDIR_/ufw-agent" 2>/dev/null && [ -s "$TMPDIR_/ufw-agent" ]; then
    install -m 0755 -o root -g root "$TMPDIR_/ufw-agent" "$AGENT"
  else
    _src=$(dirname "$0")
    [ -f "$_src/ufw-agent" ] \
      || die "ufw-agent not found next to this script (expected $_src/ufw-agent)"
    install -m 0755 -o root -g root "$_src/ufw-agent" "$AGENT"
  fi

  # The rollback helper replays the plan the agent wrote. Its argv is fixed, so
  # nothing a client sends ever reaches systemd-run's command line.
  cat > "$ROLLBACK" <<EOF
#!/bin/sh
# Fired by the deadman timer when the app fails to check in after a change.
set -eu
PLAN=$STATE_DIR/rollback.json
[ -f "\$PLAN" ] || exit 0
logger -t ufw-reloaded "rollback timer fired; restoring previous ruleset"
$AGENT --client=rollback --replay-plan
rm -f "\$PLAN"
EOF
  chown 0:0 "$ROLLBACK"
  chmod 0755 "$ROLLBACK"
  ok "agent installed to $AGENT"

  # Catch a broken agent now, not on first connect.
  if printf '{"magic":"ufw-reloaded","protocolVersion":1,"op":"ping"}' | "$AGENT" --client=selftest >/dev/null 2>&1; then
    ok "agent self-check passed"
  else
    die "agent self-check failed; refusing to continue"
  fi
}

open_firewall_port() {
  # The agent's own port has to be reachable through the firewall it manages.
  # Recorded in the manifest so uninstall can offer to remove exactly this rule.
  if [ -n "$FROM_CIDR" ]; then
    ufw allow from "$FROM_CIDR" to any port "$PORT" proto tcp comment "ufw-reloaded agent" >/dev/null
    ok "firewall: allow $PORT/tcp from $FROM_CIDR"
  else
    ufw allow "$PORT"/tcp comment "ufw-reloaded agent" >/dev/null
    ok "firewall: allow $PORT/tcp"
    # Key-only auth means nobody gets in, but MaxStartups is 3:50:10 — three
    # connections from anywhere are enough to make your own app start getting
    # refused. Losing the management port is the failure this project exists to
    # prevent, so say so rather than leaving it to the docs.
    warn "port $PORT is reachable from anywhere. Reinstalling with"
    warn "    --from <cidr> restricts it to your own network."
  fi
}

write_manifest() {
  cat > "$MANIFEST" <<EOF
version=$INSTALLER_VERSION
installedAt=$(date -u +%Y-%m-%dT%H:%M:%SZ)
port=$PORT
listen=${LISTEN:-any}
fromCidr=${FROM_CIDR:-any}
agent=$AGENT
rollback=$ROLLBACK
sshdConfig=$SSHD_CONFIG
hostKey=$HOST_KEY
authorizedKeys=$AUTH_KEYS
keysDir=$KEYS_DIR
stateDir=$STATE_DIR
unit=$UNIT
firewallRuleAdded=yes
systemSshdModified=no
EOF
  chown 0:0 "$MANIFEST"
  chmod 0644 "$MANIFEST"
}

do_install() {
  # Checked before anything is created. Discovering a missing key only at the
  # final step would leave a half-installed host: files written, host key
  # generated, firewall port opened, and no way in.
  [ -n "$PUBKEY" ] || die "--pubkey is required (the app generates one for you)"

  preflight

  # Format-check the key now that preflight has confirmed ssh-keygen exists,
  # still before anything is created.
  validate_pubkey "$PUBKEY"

  say "Installing..."
  # Order matters: every step is safe if the next one never happens, and
  # authorized_keys is written LAST because it is the step that opens access.
  install_agent_files

  if [ ! -f "$HOST_KEY" ]; then
    ssh-keygen -q -t ed25519 -N '' -f "$HOST_KEY" -C "ufw-reloaded@$(hostname)"
    chmod 0600 "$HOST_KEY"
    ok "host key generated"
  else
    ok "host key already present (reused)"
  fi

  write_sshd_config
  write_unit
  open_firewall_port
  write_manifest
  add_key

  systemctl enable --now "$SERVICE" >/dev/null 2>&1 || die "failed to start $SERVICE"
  sleep 1
  systemctl is-active --quiet "$SERVICE" || {
    warn "service failed to start; recent log:"
    journalctl -u "$SERVICE" -n 20 --no-pager >&2 || true
    die "install incomplete"
  }
  ok "service running on port $PORT"

  print_summary
}

print_summary() {
  _hostfp=$(ssh-keygen -l -f "$HOST_KEY.pub" 2>/dev/null | awk '{print $2}')
  say ""
  say "================================================================"
  say " ufw-reloaded agent installed"
  say "================================================================"
  say ""
  say " Port:              $PORT"
  say " Server host key:   $_hostfp"
  say ""
  say " Compare that fingerprint against the one the app shows when it"
  say " first connects. They must match."
  say ""
  say " Enrolled key:      $(fingerprint_of "$PUBKEY")"
  say ""
  say " Compare that against the fingerprint shown in the app too — it is"
  say " what catches a key substituted in your clipboard."
  say ""
  say " Created:"
  info "$AGENT               root:root 0755"
  info "$ROLLBACK            root:root 0755"
  info "$ETC_DIR/            root:root 0700  (config, host key, enrolled keys)"
  info "$STATE_DIR/          root:root 0700  (parked rules, snapshots)"
  info "$UNIT   root:root 0644"
  info "ufw rule allowing $PORT/tcp"
  say ""
  say " NOT touched: /etc/ssh/sshd_config, your SSH on port 22, and every"
  say " firewall rule you already had."
  say ""
  say " Uninstall:  sudo sh install.sh --uninstall"
  say "================================================================"
}

# ----------------------------------------------------------------- uninstall

do_uninstall() {
  need_root
  [ -f "$MANIFEST" ] || warn "no manifest found; removing known paths anyway"

  say "Uninstalling..."
  # Exact reverse of install: cut access first, so a failure part-way through
  # leaves a host that is unreachable-but-safe rather than reachable-but-broken.
  rm -f "$AUTH_KEYS" && ok "access revoked (authorized_keys removed)"

  systemctl disable --now "$SERVICE" >/dev/null 2>&1 || true
  systemctl stop ufw-reloaded-rollback.timer >/dev/null 2>&1 || true
  systemctl reset-failed ufw-reloaded-rollback.timer >/dev/null 2>&1 || true
  ok "service stopped and disabled"

  rm -f "$UNIT"
  systemctl daemon-reload
  ok "systemd unit removed"

  _port=$DEFAULT_PORT
  _cidr=any
  if [ -f "$MANIFEST" ]; then
    _port=$(sed -n 's/^port=//p' "$MANIFEST" | head -1)
    _cidr=$(sed -n 's/^fromCidr=//p' "$MANIFEST" | head -1)
  fi
  [ -n "$_port" ] || _port=$DEFAULT_PORT
  [ -n "$_cidr" ] || _cidr=any

  if [ "$ASSUME_YES" = 1 ]; then
    _remove_rule=y
  else
    printf 'Remove the firewall rule allowing port %s? [y/N] ' "$_port"
    read -r _remove_rule || _remove_rule=n
  fi
  case "$_remove_rule" in
    [yY]*)
      # Delete by spec, and by the SAME spec that was added — a source-scoped
      # rule is a different rule to ufw, and deleting the wrong one would either
      # fail silently or remove something we never created.
      if [ "$_cidr" = any ]; then
        ufw --force delete allow "$_port"/tcp >/dev/null 2>&1 || true
      else
        ufw --force delete allow from "$_cidr" to any port "$_port" proto tcp >/dev/null 2>&1 || true
      fi
      ok "firewall rule for $_port removed"
      ;;
    *) info "firewall rule for $_port left in place" ;;
  esac

  rm -rf "$LIB_DIR" "$ETC_DIR" "$STATE_DIR" /run/ufw-reloaded
  ok "files removed"

  say ""
  say "Done. No user account was created by this installer, so none was removed."
  say "Your ufw rules are otherwise unchanged — run 'ufw status' to review them."
}

do_status() {
  need_root
  [ -f "$MANIFEST" ] || die "agent is not installed"
  say "ufw-reloaded agent"
  info "version:  $(sed -n 's/^version=//p' "$MANIFEST")"
  info "port:     $(sed -n 's/^port=//p' "$MANIFEST")"
  info "service:  $(systemctl is-active "$SERVICE" 2>/dev/null || echo inactive)"
  info "host key: $(ssh-keygen -l -f "$HOST_KEY.pub" 2>/dev/null | awk '{print $2}')"
  say ""
  list_keys
}

# ---------------------------------------------------------------------- main

usage() {
  sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

main() {
  TMPDIR_=$(mktemp -d) || die "cannot create a temporary directory"
  chmod 0700 "$TMPDIR_"
  trap 'rm -rf "$TMPDIR_"' EXIT INT TERM

  while [ $# -gt 0 ]; do
    case "$1" in
      --pubkey)      PUBKEY=${2:-}; shift 2 ;;
      --pubkey-file) PUBKEY_FILE=${2:-}; shift 2 ;;
      --label)       LABEL=${2:-}; shift 2 ;;
      --port)        PORT=${2:-}; shift 2 ;;
      --from)        FROM_CIDR=${2:-}; shift 2 ;;
      --listen)      LISTEN=${2:-}; shift 2 ;;
      --add-key)     ACTION=add-key; shift ;;
      --remove-key)  ACTION=remove-key; LABEL=${2:-}; shift 2 ;;
      --list-keys)   ACTION=list-keys; shift ;;
      --status)      ACTION=status; shift ;;
      --uninstall)   ACTION=uninstall; shift ;;
      --yes|-y)      ASSUME_YES=1; shift ;;
      --help|-h)     usage 0 ;;
      *)             die "unknown option: $1 (try --help)" ;;
    esac
  done

  # A public key contains spaces, which makes it awkward to pass through some
  # shells intact — PowerShell in particular strips embedded quotes on the way
  # to a native command, splitting the key into separate arguments. Reading it
  # from a file sidesteps quoting entirely.
  if [ -n "$PUBKEY_FILE" ]; then
    [ -r "$PUBKEY_FILE" ] || die "cannot read $PUBKEY_FILE"
    PUBKEY=$(head -1 "$PUBKEY_FILE")
    [ -n "$PUBKEY" ] || die "$PUBKEY_FILE is empty"
  fi

  case "$PORT" in
    ''|*[!0-9]*) die "--port must be a number" ;;
  esac
  [ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] || die "--port out of range"

  SSHD_BIN=$(command -v sshd || echo /usr/sbin/sshd)

  case "$ACTION" in
    install)     do_install ;;
    add-key)     need_root; add_key; systemctl reload "$SERVICE" >/dev/null 2>&1 || true ;;
    remove-key)  need_root; remove_key "$LABEL" ;;
    list-keys)   need_root; list_keys ;;
    status)      do_status ;;
    uninstall)   do_uninstall ;;
  esac
}

main "$@"

