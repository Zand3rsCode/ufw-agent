AUTHKEYS_BIN="$LIB_DIR/ufw-authkeys"
PAIR_CLOSE="$LIB_DIR/ufw-pair-close"
UNIT=/etc/systemd/system/ufw-reloaded.service
SERVICE=ufw-reloaded.service
PAIR_TIMER=ufw-reloaded-pair-close

# The pairing bootstrap key. THE PRIVATE HALF OF THIS IS PUBLISHED, in the app
# and in this project's source, and that is deliberate.
#
# sshd will not run a forced command for a client presenting no key, and during
# a pairing window there is by definition no enrolled key yet. So the window
# opens a door with a key everyone already has and puts the lock somewhere else:
# the forced command behind it reaches one operation, which demands the pairing
# code. Possession of this key buys an attacker five guesses at 88 bits of
# os.urandom, while a window happens to be open, and nothing else. When the
# window closes the line is removed and the door does not exist.
#
# docs/SECURITY.md has the full argument. Do not reuse this key for anything.
BOOTSTRAP_PUBKEY="ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIExbrZeCjOUe6Gt4Bl7DBaabWeE5J19Os3CmpkVDnaJJ ufw-reloaded-pairing-bootstrap"

DEFAULT_PAIR_WINDOW=15
DEFAULT_PAIR_ATTEMPTS=5

PORT="$DEFAULT_PORT"
PUBKEY=""
PUBKEY_FILE=""
LABEL=""
FROM_CIDR=""
LISTEN=""
ACTION=install
ASSUME_YES=0
PAIR_WINDOW="$DEFAULT_PAIR_WINDOW"
PAIR_CANCEL=0
# Set when the install should end by opening a pairing window rather than
# enrolling a key handed to us on the command line.
PAIRING_MODE=0

# ---------------------------------------------------------------- utilities

say()  { printf '%s\n' "$*"; }
info() { printf '  %s\n' "$*"; }
ok()   { printf '  [ok] %s\n' "$*"; }
warn() { printf '  [!]  %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

need_root() {
  [ "$(id -u)" = 0 ] || die "must run as root (try: sudo sh $0 ...)"
}

have() { command -v "$1" >/dev/null 2>&1; }

